  assert.equal(await page.locator('#food-value').innerText(), '14%');
  await page.locator('#demo-guide-next').click();
  assert.match(await page.locator('#demo-guide-title').innerText(), /caregiver/);
  await page.locator('#demo-guide-back').click();
  assert.match(await page.locator('#demo-guide-title').innerText(), /signal/);
  await page.locator('#demo-guide-next').click();
  await page.locator('#demo-guide-next').click();
  assert.equal(await page.locator('#demo-guide-step').innerText(), 'STEP 4 OF 4');
  await page.locator('#classify-sample').click();
  assert.match(await page.locator('#photo-demo-result').innerText(), /Brown tabby[\s\S]*White chin[\s\S]*Mango/);
  assert.equal(await page.locator('#rescue-cat-count').innerText(), '14');
  await page.locator('#review-photo-demo').click();
  await page.locator('#review-alias').filter({ visible: true }).waitFor();
  assert.equal(await page.locator('#demo-guide').isVisible(), false);
  assert.equal(await page.locator('#review-alias').inputValue(), 'Stripey');
  assert.equal(await page.locator('.inbox-update').count(), 6);
  await page.locator('#review-evidence').fill('Compared the sample white chin and tabby markings with Mango’s existing record.');
  await page.locator('#confirm-update').click();
  await page.locator('#review-receipt').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#rescue-cat-count').innerText(), '14');
  assert.match(await page.locator('#review-receipt').innerText(), /Mango/);
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('#classify-sample').click();
  await page.locator('#review-photo-demo').click();
  await page.locator('#review-receipt').waitFor({ state: 'visible' });
  assert.match(await page.locator('#review-receipt').innerText(), /Mango/);
  assert.equal(await page.locator('.inbox-update').count(), 6);

  await page.locator('#demo-field-note').click();
  await page.locator('#phone-update-author').fill('Demo caregiver');
  await page.locator('#phone-update-text').fill('Checked the fictional shelter and left dry supplies for the next visit.');
  await page.locator('#phone-update-form [type=submit]').click();
  await page.locator('#phone-update-dialog').waitFor({ state: 'hidden' });
