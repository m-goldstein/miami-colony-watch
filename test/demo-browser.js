  await page.locator('#review-photo-demo').click();
  await page.locator('#photo-demo-status').filter({ hasText: 'unavailable' }).waitFor();
  assert.equal(await page.locator('#review-photo-demo').isEnabled(), true);
  assert.deepEqual(errors, []);
  console.log('PASS: map-first layout, guided tour, sensor scenario, sample classification → saved identity review → reload, journal note/visit persistence, physical-record isolation, five responsive widths, and unavailable-journal recovery.');
